import { readFile, writeFile } from "node:fs/promises";

const repoRoot = new URL("../", import.meta.url);
const outputPath = new URL("src/data/leetcode-contest-ratings.ts", repoRoot);
const defaultSourceUrl =
  "https://raw.githubusercontent.com/zerotrac/leetcode_problem_rating/main/data.json";
const sourceUrl = optionValue("source", defaultSourceUrl);
const inputUrl = optionValue("input", sourceUrl);

function optionValue(name, fallback) {
  const prefix = `--${name}=`;
  const option = process.argv.find((item) => item.startsWith(prefix));
  return option ? option.slice(prefix.length) : fallback;
}

function stringField(row, key) {
  const value = row?.[key];
  return typeof value === "string" ? value.trim() : "";
}

function numberField(row, key) {
  const value = Number(row?.[key]);
  return Number.isFinite(value) ? value : null;
}

function normalizeRating(row) {
  const rating = numberField(row, "Rating");
  return rating === null ? null : Math.round(rating);
}

function normalizeEntry(row) {
  const titleSlug = stringField(row, "TitleSlug");
  const rating = normalizeRating(row);
  const frontendId = numberField(row, "ID");
  if (!titleSlug || rating === null || frontendId === null) return null;
  return {
    frontendId: String(frontendId),
    titleCn: stringField(row, "TitleZH"),
    titleSlug,
    rating,
    contestSlug: stringField(row, "ContestSlug"),
    contestTitle: stringField(row, "ContestID_zh"),
    contestTitleEn: stringField(row, "ContestID_en"),
    problemIndex: stringField(row, "ProblemIndex"),
  };
}

function generatedDate() {
  return new Date().toISOString().slice(0, 10);
}

function sourceHeader() {
  return [
    "/*",
    " * Generated by scripts/sync-leetcode-contest-ratings.mjs.",
    " * Data source: https://github.com/zerotrac/leetcode_problem_rating",
    " */",
    "",
  ].join("\n");
}

function renderDataFile(entries) {
  const ratings = Object.fromEntries(
    entries.map((entry) => [entry.titleSlug, entry]),
  );
  return `${sourceHeader()}export interface LeetcodeContestRating {
  frontendId: string;
  titleCn: string;
  titleSlug: string;
  rating: number;
  contestSlug: string;
  contestTitle: string;
  contestTitleEn: string;
  problemIndex: string;
}

export const leetcodeContestRatingSource =
  "zerotrac/leetcode_problem_rating";

export const leetcodeContestRatingSourceUrl =
  "https://github.com/zerotrac/leetcode_problem_rating";

export const leetcodeContestRatings = (${JSON.stringify(ratings, null, 2)}) satisfies Record<string, LeetcodeContestRating>;

export const leetcodeContestRatingStats = {
  "generatedAt": "${generatedDate()}",
  "ratings": ${entries.length},
  "source": leetcodeContestRatingSource,
  "sourceUrl": leetcodeContestRatingSourceUrl,
  "rawDataUrl": "${sourceUrl}"
} as const;
`;
}

async function fetchRows() {
  const response = await fetch(inputUrl, {
    headers: {
      accept: "application/json",
      "user-agent": "WineChord Books LeetCode rating sync",
    },
    signal: AbortSignal.timeout(60000),
  });
  if (!response.ok) {
    throw new Error(`Failed to fetch ratings: HTTP ${response.status}`);
  }
  const rows = await response.json();
  if (!Array.isArray(rows)) {
    throw new Error("Rating source did not return an array");
  }
  return rows;
}

async function readRows() {
  if (/^https?:\/\//u.test(inputUrl)) {
    return fetchRows();
  }
  const sourcePath = inputUrl.startsWith("file:")
    ? new URL(inputUrl)
    : inputUrl;
  const rows = JSON.parse(await readFile(sourcePath, "utf8"));
  if (!Array.isArray(rows)) {
    throw new Error("Rating source did not contain an array");
  }
  return rows;
}

const rows = await readRows();
const entries = rows
  .map(normalizeEntry)
  .filter(Boolean)
  .sort((left, right) => {
    const leftId = Number(left.frontendId);
    const rightId = Number(right.frontendId);
    return leftId - rightId || left.titleSlug.localeCompare(right.titleSlug);
  });

await writeFile(outputPath, renderDataFile(entries));
console.log(
  `Synced ${entries.length} LeetCode contest ratings to ${outputPath.pathname}`,
);
